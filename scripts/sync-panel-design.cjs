// Mechanical export: LuCI remains the source of truth for the Fast Lane design.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const resources = 'luci-app-fastlane/htdocs/luci-static/resources/';
const sources = [resources+'view/fastlane/vpn-20260910-hide-keywords-v27.js', resources+'fastlane/fastlane-20260906-v4.js'];
const css = sources.map(source => {
  const text = fs.readFileSync(path.join(root, source), 'utf8');
  const template = text.match(/var css = (`[\s\S]*?`);/);
  if (!template || template[1].includes('${')) throw Error('Expected static CSS: '+source);
  return '/* Source: '+source+' */\n'+vm.runInNewContext(template[1])+Array.from(text.matchAll(/^css \+= ('[^\n]*');$/gm), m => vm.runInNewContext(m[1])).join('\n');
}).join('\n');
const files = new Map([
  ['internal/managementhttp/web/legacy.css', Buffer.from('/* Generated by scripts/sync-panel-design.cjs; do not edit. */\n'+css)],
  ['internal/managementhttp/web/legacy-brand.png', fs.readFileSync(path.join(root, resources+'fastlane/assets/fastlane-mark.png'))]
]);
const vpn = fs.readFileSync(path.join(root,sources[0]),'utf8');
const icon = vpn.slice(vpn.indexOf('function icon(name) {'),vpn.indexOf('\nvar css ='));
if(!icon.startsWith('function icon(name) {'))throw Error('Missing shared icon renderer');
files.set('internal/managementhttp/web/legacy-icons.js',Buffer.from('// Generated from the LuCI VPN icon renderer; do not edit.\nwindow.fastlaneIcon = '+icon.trim()+';\n'));
for (const [name, content] of files) {
  const target = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || !fs.readFileSync(target).equals(content)) throw Error('Run node scripts/sync-panel-design.cjs: '+name);
  } else fs.writeFileSync(target, content);
}
